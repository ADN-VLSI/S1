module s1_uart_rx_tb;

  //////////////////////////////////////////////////////////////////////////////////////////////////
  // SIGNAL DECLARATIONS
  //////////////////////////////////////////////////////////////////////////////////////////////////

  ////////////////////////////////////////////////
  // DUT Signals
  ////////////////////////////////////////////////

  logic arst_ni;
  logic clk_i;

  logic ptp_i;
  logic pen_i;
  logic [1:0] db_i;

  logic [7:0] data_o;
  logic data_err_o;
  logic data_valid_o;

  logic rx_i;

  ////////////////////////////////////////////////
  // Internal Variables
  ////////////////////////////////////////////////

  realtime TP = 8.68us;  // Corresponds to 115200 baud rate

  //////////////////////////////////////////////////////////////////////////////////////////////////
  // INTERFACE DECLARATIONS
  //////////////////////////////////////////////////////////////////////////////////////////////////

  s1_uart_if intf ();

  //////////////////////////////////////////////////////////////////////////////////////////////////
  // DUT INSTANTIATION
  //////////////////////////////////////////////////////////////////////////////////////////////////

  s1_uart_rx u_dut (.*);

  //////////////////////////////////////////////////////////////////////////////////////////////////
  // COMBINATIONAL LOGIC
  //////////////////////////////////////////////////////////////////////////////////////////////////

  assign rx_i = intf.tx;

  //////////////////////////////////////////////////////////////////////////////////////////////////
  // METHODS
  //////////////////////////////////////////////////////////////////////////////////////////////////

  task automatic apply_reset();
    #5ns;
    arst_ni <= '0;
    ptp_i   <= '0;
    pen_i   <= '0;
    db_i    <= '0;
    #5ns;
    arst_ni <= '1;
    #5ns;
  endtask

  task automatic start_clock();
    realtime sample_time;
    fork
      forever begin
        sample_time = TP / 8; // 4x2
        clk_i <= '1;
        #(sample_time);
        clk_i <= '0;
        #(sample_time);
      end
    join_none
    @(posedge clk_i);
  endtask

  ///////////////////////////////////// UART INTERFACE METHODS /////////////////////////////////////
  // task automatic send_tx(DATA, baud_rate, parity_enable, parity_type, second_stop_bit, data_bits)

  task automatic send(input logic [7:0] data, input logic ptp, input logic pen,
                      input logic [1:0] db, input int baud_rate);
    TP    <= 1s / baud_rate;
    ptp_i <= ptp;
    pen_i <= pen;
    db_i  <= db;
    repeat ($urandom_range(8, 20)) @(posedge clk_i);
    intf.send_tx(data, baud_rate, pen, ptp, 0, 5+db);
    intf.send_tx(data, baud_rate, pen, ptp, 0, 5+db);
    intf.send_tx(data, baud_rate, pen, ptp, 0, 5+db);
    intf.wait_till_idle();
    repeat (5) @(posedge clk_i);
  endtask

  //////////////////////////////////////////////////////////////////////////////////////////////////
  // PROCEDURAL BLOCKS
  //////////////////////////////////////////////////////////////////////////////////////////////////

  initial begin

    $dumpfile("s1_uart_rx_tb.vcd");
    $dumpvars(0, s1_uart_rx_tb);

    apply_reset();
    start_clock();

    send(8'hA5, 0, 0, 2'b11, 115200);  // Send 8 data bits, no parity
    send(8'h5A, 1, 1, 2'b10, 115200);  // Send 7 data bits, even parity
    send(8'h3C, 1, 1, 2'b01, 115200);  // Send 6 data bits, odd parity


    $finish();

  end


endmodule
